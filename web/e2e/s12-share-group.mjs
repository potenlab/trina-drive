// S12 (plan 5): the admin shares /재무 with the 재무 group as Viewer from the share dialog (Folder access → Share).
// sam (재무) then sees it in Team folders and search; mina (not 재무) finds nothing — the list, search and a direct
// link answer exactly as for a folder that does not exist.
import { check, shot, signedIn } from './lib.mjs'

export async function s12(browser, fx) {
  console.log('S12 share /재무 with the 재무 group (Viewer): sam sees it, mina sees nothing')
  const boss = await signedIn(browser, fx, 'boss')
  await boss.goto(fx.base + '/#/folders')
  await boss.locator('table.list a.strong', { hasText: '재무' }).click()
  await boss.locator('.page-head button', { hasText: 'Share' }).click()
  await boss.waitForSelector('.sd-body')
  check(await boss.locator('.sd-entry').count() === 0, 'restricted at first: nobody in People with access')
  await boss.fill('.sd-combo input', '재무')
  await boss.locator('.sd-options li', { hasText: '재무' }).click()
  check(await boss.locator('.sd-add-row .sd-role').inputValue() === 'viewer', 'Viewer is the default role')
  const roles = await boss.locator('.sd-add-row .sd-role option').allTextContents()
  check(roles.includes('Manager'), 'an admin is offered Manager')
  await boss.locator('.sd-add-foot button', { hasText: 'Share' }).click()
  await boss.locator('.sd-note', { hasText: 'Access updated.' }).waitFor()
  check(await boss.locator('.sd-entry', { hasText: '재무' }).locator('.sd-role').inputValue() === 'viewer', '재무 · Viewer listed')
  await shot(boss, 's12-shared-with-group')
  await boss.keyboard.press('Escape')
  await boss.context().close()

  const sam = await signedIn(browser, fx, 'sam')
  await sam.goto(fx.base + '/#/files')
  await sam.locator('.fv-items .fv-name', { hasText: '재무' }).waitFor()
  check(true, 'sam sees 재무 in Team folders')
  await sam.fill('.tb-search input', 'CANARY-FIN-7731')
  await sam.press('.tb-search input', 'Enter')
  await sam.locator('.fv-hits li', { hasText: '결산 2026 Q3.md' }).waitFor()
  check(true, 'sam finds the 재무 file by its text')
  await sam.goto(fx.base + '/#/shared')
  await sam.locator('table.swm', { hasText: '재무' }).waitFor()
  check(true, 'Shared with me lists 재무 for sam')
  await sam.context().close()

  const mina = await signedIn(browser, fx, 'mina')
  await mina.goto(fx.base + '/#/files')
  await mina.waitForSelector('.fv-items')
  check(!(await mina.locator('.fv-items .fv-name').allTextContents()).includes('재무'), 'mina: no 재무 in Team folders')
  check(!(await mina.locator('.tr-row').allTextContents()).some((x) => x.includes('재무')), 'mina: no 재무 in the sidebar tree')
  await mina.fill('.tb-search input', 'CANARY-FIN-7731')
  await mina.press('.tb-search input', 'Enter')
  await mina.locator('.fv-state', { hasText: 'Nothing found.' }).waitFor()
  check(true, 'mina: the search finds nothing')
  await mina.goto(fx.base + '/#/files?p=' + encodeURIComponent('/재무'))
  const hidden = await mina.locator('.fv-state[role=alert]').textContent()
  await mina.goto(fx.base + '/#/files?p=' + encodeURIComponent('/없는폴더'))
  const missing = await mina.locator('.fv-state[role=alert]').textContent()
  check(hidden === missing && /not there/.test(hidden ?? ''), 'mina: a direct link to /재무 reads like a folder that does not exist')
  const a = await mina.request.get(fx.base + '/api/files?path=' + encodeURIComponent('/재무'))
  const b = await mina.request.get(fx.base + '/api/files?path=' + encodeURIComponent('/없는폴더'))
  check(a.status() === b.status() && (await a.text()) === (await b.text()), 'mina: the API answer for /재무 is byte-for-byte the missing one')
  check(mina.errors.length === 0, 'no page errors' + (mina.errors.length ? ': ' + mina.errors.join(' | ') : ''))
  await mina.context().close()
}
